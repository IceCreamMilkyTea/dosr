#!/usr/bin/env python3
"""Turns eval/results/raw/*.json (written by dosr-bench) into figures and a
Markdown summary: eval/results/figures/*.png and eval/results/SUMMARY.md.

    python3 eval/plot.py [raw_dir] [out_dir]
"""
import glob, json, os, sys
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

RAW = sys.argv[1] if len(sys.argv) > 1 else "eval/results/raw"
OUT = sys.argv[2] if len(sys.argv) > 2 else "eval/results"
FIG = os.path.join(OUT, "figures")
os.makedirs(FIG, exist_ok=True)

# Brand-neutral palette (see the dataviz skill); dark-on-light figures.
C = ["#2563eb", "#dc2626", "#059669", "#d97706", "#7c3aed", "#0891b2"]
plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.grid": True, "grid.alpha": 0.3, "figure.dpi": 130})

results = {}
for f in sorted(glob.glob(os.path.join(RAW, "*.json"))):
    with open(f) as fh:
        results[os.path.basename(f)[:-5]] = json.load(fh)

md = ["# Evaluation results", "",
      "Generated by `eval/plot.py` from `eval/results/raw/*.json` (dosr-bench). "
      "All numbers: one Apple M-series laptop, 8 cores, in-process CometBFT nodes with emulated links; "
      "LLM latency is the mock provider's ASSUMED model (see `pkg/llm/model.go`). "
      "Percentiles are over accepted submissions; `commit` = broadcast admitted -> decided at the client's node; "
      "`decided_all` = Submit start -> last honest node committed the block; `total` = whole Submit call.", ""]

def ms(d, k="p50_ms"):
    return d.get(k, float("nan")) if isinstance(d, dict) else float("nan")

# ------------------------------------------------------------ verify cost
v = results.get("verify_cost")
if v:
    xs = [s["extra"]["change_bytes"] for s in v["samples"]]
    ys = [s["extra"]["p50_ms"] for s in v["samples"]]
    tx = [s["extra"]["tx_bytes"] for s in v["samples"]]
    fig, ax = plt.subplots(figsize=(5, 3.2))
    ax.plot(xs, ys, "o-", color=C[0])
    ax.set_xscale("log"); ax.set_yscale("log")
    ax.set_xlabel("change size (bytes)"); ax.set_ylabel("verification time, p50 (ms)")
    ax.set_title("Validator cost of verifying one AcceptCommit")
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "verify_cost.png")); plt.close(fig)
    md += ["## Verification cost (in-process, cold cache)", "",
           "| change bytes | tx bytes | p50 ms | p90 ms |", "|---|---|---|---|"]
    for s in v["samples"]:
        e = s["extra"]
        md.append(f"| {e['change_bytes']} | {e['tx_bytes']} | {e['p50_ms']:.2f} | {e['p90_ms']:.2f} |")
    md += ["", "![](figures/verify_cost.png)", ""]

# ------------------------------------------------------------ consensus
cons = {k: r for k, r in results.items() if k.startswith("consensus_")}
if cons:
    md += ["## Consensus latency vs validators and network (no LLM latency)", "",
           "| validators | network | timeouts | commit p50 | commit p90 | decided-all p50 | decided-all p90 | block interval | rounds |",
           "|---|---|---|---|---|---|---|---|---|"]
    for tn in ["default", "fast"]:
        fig, ax = plt.subplots(figsize=(6, 3.4))
        nets = ["lan", "regional", "wan"]
        for ci, nw in enumerate(nets):
            pts = []
            for k, r in sorted(cons.items()):
                p = r["params"]
                if p["network"] == nw and p.get("timeouts") == tn:
                    pts.append((p["validators"], ms(r["summary"]["decided_all"]), ms(r["summary"]["decided_all"], "p90_ms")))
            if pts:
                pts.sort()
                ax.errorbar([p[0] for p in pts], [p[1] for p in pts],
                            yerr=[[0]*len(pts), [p[2]-p[1] for p in pts]], fmt="o-", color=C[ci], label=nw, capsize=3)
        ax.set_xlabel("validators"); ax.set_ylabel("Submit -> all nodes committed, p50 (ms), bar to p90")
        ax.set_title(f"Propagation latency, {tn} timeouts"); ax.legend()
        fig.tight_layout(); fig.savefig(os.path.join(FIG, f"consensus_{tn}.png")); plt.close(fig)
    for k, r in sorted(cons.items(), key=lambda kv: (kv[1]["params"].get("timeouts"), kv[1]["params"]["network"], kv[1]["params"]["validators"])):
        p, s = r["params"], r["summary"]
        md.append(f"| {p['validators']} | {p['network']} | {p.get('timeouts')} | {ms(s['commit']):.0f} | {ms(s['commit'],'p90_ms'):.0f} | "
                  f"{ms(s['decided_all']):.0f} | {ms(s['decided_all'],'p90_ms'):.0f} | {s.get('block_interval','')} | {s.get('rounds_histogram')} |")
    md += ["", "![](figures/consensus_default.png) ![](figures/consensus_fast.png)", ""]

# ------------------------------------------------------------ bundle size
bun = {k: r for k, r in results.items() if k.startswith("bundle_")}
if bun:
    pts = sorted((r["params"]["change_bytes"], ms(r["summary"]["commit"]), ms(r["summary"]["commit"], "p90_ms"),
                  r["summary"]["avg_tx_bytes"], ms(r["summary"]["client_prepare"])) for r in bun.values())
    fig, ax = plt.subplots(figsize=(5, 3.2))
    ax.plot([p[0] for p in pts], [p[1] for p in pts], "o-", color=C[0], label="commit p50")
    ax.plot([p[0] for p in pts], [p[2] for p in pts], "s--", color=C[1], label="commit p90")
    ax.set_xscale("log"); ax.set_xlabel("change size (bytes)"); ax.set_ylabel("ms")
    ax.set_title("Commit latency vs bundle size (4 validators, regional)"); ax.legend()
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "bundle_size.png")); plt.close(fig)
    md += ["## Commit latency vs change size (bundle inside the transaction)", "",
           "| change bytes | avg tx bytes | client prepare p50 ms | commit p50 ms | commit p90 ms |", "|---|---|---|---|---|"]
    for p in pts:
        md.append(f"| {p[0]} | {p[3]:.0f} | {p[4]:.2f} | {p[1]:.0f} | {p[2]:.0f} |")
    md += ["", "![](figures/bundle_size.png)", ""]

# ------------------------------------------------------------ e2e breakdown
e2e = {k: r for k, r in results.items() if k.startswith("e2e_") and not k.startswith("e2e_size_")}
if e2e:
    md += ["## End-to-end latency breakdown and cost: DOSR vs every-validator-reviews", "",
           "| mode | LLM latency | accepted | total p50 | total p90 | LLM call p50 | attest overhead p50 | commit p50 | rounds | provider calls | calls / accepted | cost USD |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    labels, parts = [], []
    for k, r in sorted(e2e.items()):
        p, s = r["params"], r["summary"]
        pv = s["provider"]
        md.append(f"| {p['mode']} | {p['latency']} | {s['ok']}/{p['count']} | {ms(s['total']):.0f} | {ms(s['total'],'p90_ms'):.0f} | "
                  f"{ms(s['llm_upstream']):.0f} | {ms(s['attest_overhead']):.1f} | {ms(s['commit']):.0f} | {s.get('rounds_histogram')} | "
                  f"{pv['calls']} | {s['llm_calls_per_accepted']:.1f} | {pv['cost_usd']:.4f} |")
        labels.append(f"{p['mode']}\n{p['latency']}")
        parts.append((ms(s["client_prepare"]), ms(s["llm_upstream"]), ms(s["attest_overhead"]), ms(s["commit"])))
    fig, ax = plt.subplots(figsize=(6, 3.4))
    bottom = [0]*len(parts)
    for i, (nm, col) in enumerate([("client prepare", C[4]), ("LLM call", C[1]), ("attestation", C[3]), ("consensus commit", C[0])]):
        vals = [p[i] for p in parts]
        ax.bar(labels, vals, bottom=bottom, color=col, label=nm)
        bottom = [b+v for b, v in zip(bottom, vals)]
    ax.set_ylabel("p50 ms"); ax.set_title("End-to-end latency breakdown (4 validators, WAN)"); ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "e2e_breakdown.png")); plt.close(fig)
    md += ["", "In baseline mode validators call the LLM while forming their vote; the 'commit' column then contains the validators' LLM calls "
           "(the notes column 'rounds' shows how many consensus rounds each block needed).", "", "![](figures/e2e_breakdown.png)", ""]

# ------------------------------------------------------------ e2e vs change size
e2s = {k: r for k, r in results.items() if k.startswith("e2e_size_")}
if e2s:
    rows = sorted(e2s.values(), key=lambda r: r["params"]["change_bytes"])
    md += ["## End-to-end latency vs change size (DOSR, 4 validators, WAN, default timeouts, ASSUMED realistic LLM latency)", "",
           "| change bytes | request bytes | tx bytes | accepted | client prepare p50 ms | LLM call p50 ms | attest overhead p50 ms | admit p50 ms | commit p50 ms | total p50 ms | total p90 ms | decided_all p50 ms |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    labels, parts, dall = [], [], []
    for r in rows:
        p, s = r["params"], r["summary"]
        md.append(f"| {p['change_bytes']} | {s['avg_request_bytes']:.0f} | {s['avg_tx_bytes']:.0f} | {s['ok']}/{p['count']} | {ms(s['client_prepare']):.2f} | "
                  f"{ms(s['llm_upstream']):.0f} | {ms(s['attest_overhead']):.1f} | {ms(s.get('admit', {})):.1f} | {ms(s['commit']):.0f} | "
                  f"{ms(s['total']):.0f} | {ms(s['total'],'p90_ms'):.0f} | {ms(s['decided_all']):.0f} |")
        kb = p["change_bytes"] / 1024
        labels.append(f"{kb:g} KB" if kb < 1024 else f"{kb/1024:g} MB")
        parts.append((ms(s["client_prepare"]), ms(s["llm_upstream"]), ms(s["attest_overhead"]) + ms(s.get("admit", {})), ms(s["commit"])))
        dall.append(ms(s["decided_all"]))
    fig, ax = plt.subplots(figsize=(6, 3.4))
    bottom = [0]*len(parts)
    for i, (nm, col) in enumerate([("client prepare", C[4]), ("LLM call (assumed model)", C[1]), ("attestation + admit", C[3]), ("consensus commit", C[0])]):
        vals = [p[i] for p in parts]
        ax.bar(labels, vals, bottom=bottom, color=col, label=nm, width=0.6, edgecolor="white", linewidth=1)
        bottom = [b+v for b, v in zip(bottom, vals)]
    for x, (b, d) in enumerate(zip(bottom, dall)):
        ax.text(x, b, f"{b/1000:.1f} s", ha="center", va="bottom", fontsize=8)
    ax.set_ylabel("p50 ms"); ax.set_xlabel("change size")
    ax.set_title("End-to-end latency vs change size (4 validators, WAN)"); ax.legend(fontsize=8, loc="upper left")
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "e2e_size.png")); plt.close(fig)
    md += ["", "The LLM call is the mock provider's ASSUMED model (ttft lognormal median 1.2 s, 60 output tok/s, 50 us per input token with tokens = bytes/4); "
           "its growth with size is the per-input-token term, not a measurement of any provider. 'attest overhead' = attestor time minus the upstream call; "
           "'admit' = broadcast until CheckTx answered.", "", "![](figures/e2e_size.png)", ""]

# ------------------------------------------------------------ propagation to full nodes
prop = {k: r for k, r in results.items() if k.startswith("propagation_")}
if prop:
    rows = sorted(prop.values(), key=lambda r: r["params"]["full_nodes"])
    md += ["## Propagation to validators and non-validator full nodes (4 validators, regional, fast timeouts, no LLM latency)", "",
           "| full nodes | accepted | commit p50 ms | first validator p50 ms | last validator p50 ms | validator spread p50 / p90 / max ms | last full node p50 ms | full-node spread p50 / p90 / max ms | last full node after first validator p50 / p90 / max ms | decided_all p50 ms | block interval |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    xs, vs, fs = [], [], []
    def trio(d):
        return f"{ms(d):.1f} / {ms(d,'p90_ms'):.1f} / {ms(d,'max_ms'):.1f}" if d.get("n") else "-"
    def one(d):
        return f"{ms(d):.0f}" if d.get("n") else "-"
    for r in rows:
        p, s = r["params"], r["summary"]
        md.append(f"| {p['full_nodes']} | {s['ok']}/{p['count']} | {ms(s['commit']):.0f} | {ms(s['validator_first']):.0f} | {ms(s['validator_last']):.0f} | "
                  f"{trio(s['validator_spread'])} | {one(s['full_last'])} | {trio(s['full_spread'])} | {trio(s['full_after_first_validator'])} | "
                  f"{ms(s['decided_all']):.0f} | {s.get('block_interval','')} |")
        xs.append(p["full_nodes"]); vs.append((ms(s["validator_spread"]), ms(s["validator_spread"], "p90_ms")))
        fs.append((ms(s["full_after_first_validator"]), ms(s["full_after_first_validator"], "p90_ms")))
    fig, ax = plt.subplots(figsize=(5.5, 3.2))
    ax.errorbar(xs, [v[0] for v in vs], yerr=[[0]*len(vs), [v[1]-v[0] for v in vs]], fmt="o-", color=C[0], capsize=3, label="last validator after first validator")
    fx = [x for x, f in zip(xs, fs) if f[0] == f[0]]
    fy = [f for f in fs if f[0] == f[0]]
    if fy:
        ax.errorbar(fx, [f[0] for f in fy], yerr=[[0]*len(fy), [f[1]-f[0] for f in fy]], fmt="s--", color=C[2], capsize=3, label="last full node after first validator")
    ax.set_xlabel("non-validator full nodes (plus 4 validators)"); ax.set_ylabel("p50 ms, bar to p90"); ax.set_xticks(xs)
    ax.set_ylim(bottom=0); ax.set_title("Block propagation spread (regional, fast timeouts)"); ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "propagation.png")); plt.close(fig)
    md += ["", "Spreads are differences of the nodes' own commit timestamps (one clock, one machine) for the height that decided each submission; "
           "a full node follows consensus through the consensus reactor and commits when it has the block and +2/3 precommits.", "", "![](figures/propagation.png)", ""]

# ------------------------------------------------------------ contention
con = {k: r for k, r in results.items() if k.startswith("contention_")}
if con:
    pts = sorted((r["params"]["contributors"], r["summary"]["reviews_per_accepted"], r["summary"]["throughput_per_min"],
                  r["summary"]["accepted"], r["summary"]["provider_calls"], r["summary"]["wall_ms"]/1000, r["summary"]["cost_usd"]) for r in con.values())
    fig, ax = plt.subplots(figsize=(5, 3.2))
    ax.plot([p[0] for p in pts], [p[1] for p in pts], "o-", color=C[1])
    ax.set_xlabel("concurrent contributors on one branch"); ax.set_ylabel("LLM reviews per accepted commit")
    ax.set_title("Wasted reviews under head contention")
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "contention.png")); plt.close(fig)
    md += ["## Head contention: optimistic concurrency cost", "",
           "| contributors | accepted | reviews | reviews / accepted | wall s | accepted / min | cost USD |", "|---|---|---|---|---|---|---|"]
    for p in pts:
        md.append(f"| {p[0]} | {p[3]} | {p[4]} | {p[1]:.2f} | {p[5]:.1f} | {p[2]:.1f} | {p[6]:.4f} |")
    md += ["", "![](figures/contention.png)", ""]

# ------------------------------------------------------------ faults
fl = results.get("faults_timeline")
if fl:
    md += ["## Faults: submission latency across crash, restart, partition, heal", "",
           "| phase | n | failed | p50 ms | max ms |", "|---|---|---|---|---|"]
    order = ["healthy", "validator3_down", "validator3_restarted", "partition_3_1_minority_has_client", "partition_3_1_majority", "healed"]
    for ph in order:
        d = fl["summary"]["by_phase"].get(ph, {})
        md.append(f"| {ph} | {d.get('n',0)} | {d.get('failed',0)} | {d.get('p50_ms',float('nan')):.0f} | {d.get('max_ms',float('nan')):.0f} |")
    xs, ys, cs = [], [], []
    for s in fl["samples"]:
        if s.get("outcome") and not s.get("err"):
            xs.append(s["extra"]["at_s"]); ys.append(s["outcome"]["timeline"]["total_ns"]/1e6)
            cs.append(C[order.index(s["extra"]["phase"]) % len(C)])
    fig, ax = plt.subplots(figsize=(6, 3.2))
    ax.scatter(xs, ys, c=cs)
    for n in fl.get("notes", []):
        if "fault injected at +" in n:
            t = float(n.split("+")[1].rstrip("s"))
            ax.axvline(t, color="#999", ls=":", lw=1)
            ax.text(t, max(ys)*0.95, n.split(":")[0], rotation=90, fontsize=6, va="top")
    ax.set_xlabel("experiment time (s)"); ax.set_ylabel("Submit total (ms)"); ax.set_title("Submission latency under faults")
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "faults.png")); plt.close(fig)
    md += ["", f"Invariants after the run: {fl['summary'].get('invariants')}. Notes: {fl.get('notes')}", "", "![](figures/faults.png)", ""]

# ------------------------------------------------------------ grinding
gr = {k: r for k, r in results.items() if k.startswith("grinding_")}
if gr:
    md += ["## Approval grinding: intents + single-use nonces", "",
           "| mode | p(approve) | trials | max tries | accepted | acceptance rate | expected (unbounded) | expected (bounded) | reviews / trial | refused by chain | refused by notary |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, r in sorted(gr.items()):
        p, s = r["params"], r["summary"]
        md.append(f"| {p['mode']} | {p['p_approve']} | {p['trials']} | {p['max_tries']} | {s['accepted']} | {s['acceptance_rate']:.2f} | "
                  f"{s['expected_rate_unbounded']:.2f} | {s['expected_rate_bounded'] if p['max_attempts'] else '-'} | {s['reviews_per_trial']:.2f} | "
                  f"{s['refused_by_chain']} | {s['refused_by_notary']} |")
    md.append("")

with open(os.path.join(OUT, "SUMMARY.md"), "w") as fh:
    fh.write("\n".join(md) + "\n")
print("wrote", os.path.join(OUT, "SUMMARY.md"), "and", len(os.listdir(FIG)), "figures")
